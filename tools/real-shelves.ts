// A five-petal flower head facing us, centred on (cx, cy): one scalloped shape and its middle.
const flower = (cx: number, cy: number, r: number, petal = M, middle = A) => {
  const at = (a: number, k: number) => `${n(cx + Math.cos(a) * r * k)} ${n(cy + Math.sin(a) * r * k)}`;
  const step = (2 * Math.PI) / 5, a0 = -Math.PI / 2 - step / 2;
  const d = `M${at(a0, 0.3)}` + [0, 1, 2, 3, 4].map((i) => {
    const a = a0 + i * step;
    return ` C${at(a + step * 0.05, 1.25)} ${at(a + step * 0.95, 1.25)} ${at(a + step, 0.3)}`;
  }).join('') + ' Z';
  return P(d, petal, 'R', 1.5) + C(cx, cy, r * 0.3, middle, 'R', 1.5);
};
