// Glass: a window, and a row of them.
const win = (x: number, y: number, w: number, h: number, r = 4) =>
  `<rect x="${x}" y="${y}" width="${w}" height="${h}" rx="${r}" fill="${G}" stroke="${O}" stroke-width="1.5"/>` + (w > 20 ? s(`M${x + 4} ${y + h - 4} L${x + w * 0.45} ${y + 4}`, W, 2.5, 0.5) : '');
const wins = (x: number, y: number, w: number, h: number, k: number, gap: number) => Array.from({ length: k }, (_, i) => win(x + i * (w + gap), y, w, h, 3)).join('');
// Lights: a head lamp and a tail lamp.
const lamp = (x: number, y: number, r: number) => C(x, y, r, W, 'R', 1.5);
const tail = (x: number, y: number, w: number, h: number) => B(x, y, w, h, 2, '#ffffff', 'V', 1);
// A wheel: tyre, lit hub, axle.
const tyre = (cx: number, cy: number, r: number) => dot(cx, cy, r, K) + C(cx, cy, r * 0.6, T, 'H', 1.5) + dot(cx, cy, r * 0.2, K, 0.5);
// A rail under a ride: two lines and sleepers.
