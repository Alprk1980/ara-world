// A grid of thin lines inside a box (nets, strings, wire baskets), as one path.
const grid = (x0: number, y0: number, x1: number, y1: number, step: number, col = W, w = 1.5, op = 0.8) => {
  let d = '';
  for (let x = x0 + step; x < x1; x += step) d += `M${x} ${y0} L${x} ${y1} `;
  for (let y = y0 + step; y < y1; y += step) d += `M${x0} ${y} L${x1} ${y} `;
  return s(d.trim(), col, w, op);
};
// A football: a white ball with dark pentagon patches.
const football = (cx: number, cy: number, r: number, fill = M, patch = T) =>
  C(cx, cy, r, fill) + f([ring(cx, cy, r * 0.26, r * 0.26, 5), ...[0, 1, 2, 3, 4].map((i) => {
    const a = -Math.PI / 2 + (i * 2 * Math.PI) / 5;
    return ring(cx + Math.cos(a) * r * 0.72, cy + Math.sin(a) * r * 0.72, r * 0.2, r * 0.2, 5, () => 1, a + Math.PI / 2);
  })].join(' '), patch) +
  s([0, 1, 2, 3, 4].map((i) => {
    const a = -Math.PI / 2 + (i * 2 * Math.PI) / 5;
    return `M${cx + Math.cos(a) * r * 0.26} ${cy + Math.sin(a) * r * 0.26} L${cx + Math.cos(a) * r * 0.52} ${cy + Math.sin(a) * r * 0.52}`;
  }).join(' '), K, 1.5, 0.35) + C(cx, cy, r, M, 'R', 2.5).replace(/^<ellipse[^>]*\/>/, '');
