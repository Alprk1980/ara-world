  P(`M${cx - rx} ${cy} A${rx} ${ry} 0 1 0 ${cx + rx} ${cy} A${rx} ${ry} 0 1 0 ${cx - rx} ${cy} Z M${cx - hx} ${cy} A${hx} ${hy} 0 1 1 ${cx + hx} ${cy} A${hx} ${hy} 0 1 1 ${cx - hx} ${cy} Z`, M, 'R');

