const r = Math.round;
// A small natural eye: a dark almond with a glint.
const eye = (x: number, y: number, rx = 5, ry = 4) => oval(x, y, rx, ry, K) + dot(x - rx * 0.35, y - ry * 0.35, Math.max(1.2, ry * 0.4), W);
// A front leg seen from the side: from the body (x0..x1 at y0) it tapers to the knee, then runs thin and straight to
// the ground; foot is the hoof or paw height.
const leg = (x0: number, x1: number, y0: number, knee: number, ground: number, w: number, lean = 0) => {
  const c = r((x0 + x1) / 2 + lean), k = r(w * 0.55), b = r(w * 0.45);
  return `M${x0} ${y0} L${x1} ${y0} C${x1} ${r((y0 + knee) / 2)} ${c + k} ${knee - 12} ${c + k} ${knee} L${c + b} ${ground} L${c - b} ${ground} L${c - k} ${knee} C${c - k} ${knee - 12} ${x0} ${r((y0 + knee) / 2)} ${x0} ${y0} Z`;
};
// A hind leg seen from the side (facing left): the thigh sweeps back to the hock, then the cannon drops to the ground.
const hind = (x0: number, x1: number, y0: number, hock: number, ground: number, w: number) => {
  const h = x1 - r(w * 0.2), k = r(w * 0.5), b = r(w * 0.42), g = h - r(w * 0.4);
  return `M${x0} ${y0} L${x1} ${y0} C${x1 + 4} ${y0 + 24} ${h + k + 2} ${hock - 20} ${h + k} ${hock} L${g + b} ${ground} L${g - b} ${ground} L${h - k} ${hock} C${h - k - 6} ${hock - 18} ${x0 + 4} ${y0 + 34} ${x0} ${y0} Z`;
};
// A hoof under a leg ending at x c on the ground.
const hoof = (c: number, ground: number, w: number) => f(`M${c - w / 2} ${ground - 9} L${c + w / 2} ${ground - 9} L${c + w / 2 + 2} ${ground} L${c - w / 2 - 2} ${ground} Z`, O, 0.9);
// A leg further away: the same shape, a little darker.
const far = (d: string, fill = M) => `<path d="${d}" fill="${fill}"/><path d="${d}" fill="${K}" fill-opacity="0.2" stroke="${O}" stroke-width="1.5" stroke-linejoin="round"/>`;
// A front leg standing in front of the chest: shaded, outlined down its sides only, so it grows out of the body.
const column = (d: string, sides: string) => f(d, M) + s(sides, O, 1.8);

